def recipe(rid, category, out_item, out_level, out_amount, pattern, key):
    R.append(f"  {rid}:\n    category: {category}\n    output:\n      item: {out_item}\n")
    if out_level > 1:
        R.append(f"      tier: {out_level}\n")
