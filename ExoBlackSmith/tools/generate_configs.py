def yaml_value(v, indent):
    pad = " " * indent
    if isinstance(v, dict):
        s = "\n"
        for k, val in v.items():
            s += f"{pad}{k}:" + yaml_value(val, indent + 2)
        return s
    if isinstance(v, list):
        s = "\n"
        for item in v:
            if isinstance(item, dict):
                first = True
                for k, val in item.items():
                    s += (f"{pad}- " if first else f"{pad}  ") + f"{k}:" + yaml_value(val, indent + 4)
                    first = False
            else:
                s += f"{pad}- {yaml_scalar(item)}\n"
        return s
    return " " + yaml_scalar(v) + "\n"


def yaml_scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return q(str(v))


